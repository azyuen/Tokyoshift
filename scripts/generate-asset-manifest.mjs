// Run after changing artwork/audio; CI rejects stale manifests.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { resolve, relative } from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const entries = {};
function scan(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a,b) => a.name.localeCompare(b.name, 'en'))) {
    const path = resolve(dir, entry.name);
    if (entry.isDirectory()) scan(path);
    else if (/\.(png|jpe?g|webp|svg|gif|mp3|ogg|wav|m4a|woff2?)$/i.test(entry.name)) {
      entries[relative(root, path).replaceAll('\\', '/')] = createHash('sha256').update(readFileSync(path)).digest('hex');
    }
  }
}
scan(resolve(root, 'assets'));
for (const name of readdirSync(root).sort()) {
  if (/^app-icon.*\.(png|webp|svg)$/.test(name)) entries[name] = createHash('sha256').update(readFileSync(resolve(root,name))).digest('hex');
}
const output = '// Generated by scripts/generate-asset-manifest.mjs. Do not edit.\nself.TOKYO_SHIFT_ASSET_REVISIONS = ' + JSON.stringify(entries, null, 2) + ';\n';
const target = resolve(root, 'asset-manifest.js');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('Asset manifest is stale: run node scripts/generate-asset-manifest.mjs');
} else writeFileSync(target, output);
console.log(`${Object.keys(entries).length} asset revisions ${process.argv.includes('--check') ? 'verified' : 'written'}`);
